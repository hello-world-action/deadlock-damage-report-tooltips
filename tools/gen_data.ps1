# Generates mod\panorama\scripts\damage_row_tooltip_data.js: which damage-row keys get a
# tooltip, read from the installed game's abilities.vdata.
#   'a' = hero ability (signature / ultimate / innate) -> ability tooltip
#   'i' = item                                          -> item tooltip
# Guns, melee and anything else are left out, so those rows show no tooltip.
# Re-run after game updates that add heroes or items, then run build.ps1.
param(
    [string]$Vpk = 'C:\Program Files (x86)\Steam\steamapps\common\Deadlock\game\citadel\pak01_dir.vpk'
)
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path "$PSScriptRoot\..").Path
$s2v  = Join-Path $PSScriptRoot 's2v\Source2Viewer-CLI.exe'
$out  = Join-Path $root 'mod\panorama\scripts\damage_row_tooltip_data.js'

& $s2v -i $Vpk -f 'scripts/abilities.vdata_c' -d -o (Join-Path $root 'vanilla_src') | Out-Null

$version = 'unknown'
$inf = Join-Path (Split-Path $Vpk) 'steam.inf'
if ((Test-Path $inf) -and ((Get-Content $inf -Raw) -match 'ClientVersion=(\d+)')) { $version = $matches[1] }

$kinds = [ordered]@{}
$key = $null
foreach ($line in [IO.File]::ReadLines((Join-Path $root 'vanilla_src\scripts\abilities.vdata'))) {
    if ($line -match '^\t([A-Za-z0-9_]+) = *$') { $key = $matches[1] }
    elseif ($key -and $line -match '^\t\tm_eAbilityType = "EAbilityType_(\w+)"') {
        switch ($matches[1]) {
            'Item'      { $kinds[$key] = 'i' }
            'Signature' { $kinds[$key] = 'a' }
            'Ultimate'  { $kinds[$key] = 'a' }
            'Innate'    { $kinds[$key] = 'a' }
            default     { $kinds[$key] = 'x' }   # known, but no tooltip (guns, melee, ...)
        }
    }
}

# Ability -> owning hero, from each hero's m_mapBoundAbilities. Abilities bound to more than
# one hero (dash, jump, ...) are dropped: they do not identify an attacker.
& $s2v -i $Vpk -f 'scripts/heroes.vdata_c' -d -o (Join-Path $root 'vanilla_src') | Out-Null
$owners = @{}
$hero = $null; $inBound = $false; $sawBound = $false
foreach ($line in [IO.File]::ReadLines((Join-Path $root 'vanilla_src\scripts\heroes.vdata'))) {
    if ($line -match '^\t([A-Za-z0-9_]+) = *$') { $hero = $matches[1]; $inBound = $false }
    elseif ($line -match '^\t\tm_mapBoundAbilities = *$') { $inBound = $true; $sawBound = $true }
    elseif ($inBound -and $line -match '^\t\t\}') { $inBound = $false }
    elseif ($inBound -and $hero -and $hero -ne 'hero_base' -and $line -match '^\t\t\t\w+ = "([A-Za-z0-9_]+)"') {
        $a = $matches[1]
        if (-not $owners.ContainsKey($a)) { $owners[$a] = New-Object System.Collections.Generic.HashSet[string] }
        [void]$owners[$a].Add($hero)
    }
}
if (-not $sawBound) { throw 'heroes.vdata has no m_mapBoundAbilities blocks in the expected layout' }
$heroOf = [ordered]@{}
foreach ($a in ($owners.Keys | Sort-Object)) {
    if ($owners[$a].Count -eq 1 -and $kinds[$a] -eq 'a') { $heroOf[$a] = @($owners[$a])[0] }
}

$entries = $kinds.GetEnumerator() | Sort-Object Name | ForEach-Object { "`t$($_.Name): '$($_.Value)'" }
$heroEntries = $heroOf.GetEnumerator() | ForEach-Object { "`t$($_.Name): '$($_.Value)'" }
$js = @"
// GENERATED by tools\gen_data.ps1 - do not edit.
// Built from Deadlock client version $version.
// Every known damage-row key: 'a' = ability, 'i' = item, 'x' = no tooltip (guns, melee, ...).
// Keys missing from this table are newer than this build; the script guesses for those.
`$.DamageRowTooltipKinds = {
$($entries -join ",`n")
};
// Ability key -> the one hero that owns it.
`$.DamageRowTooltipHeroes = {
$($heroEntries -join ",`n")
};
"@
[IO.File]::WriteAllText($out, $js, (New-Object Text.UTF8Encoding $false))
$a = @($kinds.Values | Where-Object { $_ -eq 'a' }).Count
$i = @($kinds.Values | Where-Object { $_ -eq 'i' }).Count
"Wrote $out for client $version ($a abilities, $i items, $($kinds.Count - $a - $i) excluded, $($heroOf.Count) abilities mapped to a hero)"

# The layout: the game's current hud_damage_rows with our script includes injected, so a
# patch that changes the vanilla layout is picked up by regenerating instead of hand-merging.
& $s2v -i $Vpk -f 'panorama/layout/hud_damage_rows.vxml_c' -d -o (Join-Path $root 'vanilla_src') | Out-Null
$layoutSrc = Join-Path $root 'vanilla_src\panorama\layout\hud_damage_rows.xml'
$layoutOut = Join-Path $root 'mod\panorama\layout\hud_damage_rows.xml'
$layout = [IO.File]::ReadAllText($layoutSrc)
if ($layout -match '<scripts>') { throw 'vanilla hud_damage_rows now has its own <scripts> block; merge by hand' }
if ($layout -notmatch '</styles>' -or $layout -notmatch 'snippet name="AbilityDamageBar"' -or $layout -notmatch 'id="Data"') {
    throw 'vanilla hud_damage_rows no longer has the structure the mod expects (styles / AbilityDamageBar / Data)'
}
$layout = $layout -replace '(?m)^<!-- xml reconstructed by Source 2 Viewer.*-->\r?\n', ''
# Mod sources reference compiled resources by their compiled names.
$layout = $layout -replace '(src="s2r://[^"]+\.v(?:css|js|ts))"', '$1_c"'
$scripts = "</styles>`n`t<scripts>`n`t`t<include src=`"s2r://panorama/scripts/damage_row_tooltip_data.vjs_c`" />`n`t`t<include src=`"s2r://panorama/scripts/damage_row_tooltips.vjs_c`" />`n`t</scripts>"
$layout = ([regex]'</styles>').Replace($layout, $scripts, 1)
$layout = "<!-- GENERATED by tools\gen_data.ps1 from the game's hud_damage_rows (client $version) plus the tooltip scripts. -->`n" + $layout
[IO.File]::WriteAllText($layoutOut, $layout, (New-Object Text.UTF8Encoding $false))
"Wrote $layoutOut"
